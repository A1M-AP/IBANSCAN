import { spawn } from "node:child_process";
import { createServer } from "node:http";
import { createServer as createSocketServer } from "node:net";
import { createHash, randomBytes, timingSafeEqual } from "node:crypto";
import { existsSync, mkdirSync, openSync, closeSync, readFileSync, writeFileSync, renameSync, unlinkSync, readdirSync } from "node:fs";
import { resolve, dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const local = join(root, ".local");
const statePath = join(local, "preview.json");
const lockPath = join(local, "launch.lock");
const fingerprintPath = join(local, "build-fingerprint.txt");
const serverEntry = join(root, ".next", "standalone", "server.js");
const logPath = join(local, "preview.log");
const mode = process.argv[2] || "start";
const noBrowser = process.argv.includes("--no-browser");
const delay = ms => new Promise(resolveDelay => setTimeout(resolveDelay, ms));
mkdirSync(local, { recursive: true });
process.chdir(root);

function readState() {
  try {
    const state = JSON.parse(readFileSync(statePath, "utf8"));
    const url = new URL(state.url);
    if (!Number.isInteger(state.controlPort) || state.controlPort < 1024 || state.controlPort > 65535
      || !/^[a-f0-9]{64}$/.test(state.token) || url.hostname !== "127.0.0.1" || url.protocol !== "http:"
      || !/^\d+$/.test(url.port) || url.pathname !== "/" || url.search || url.hash || url.username || url.password) return null;
    return state;
  } catch { return null; }
}
async function control(state, action) {
  if (!state) return null;
  try {
    const response = await fetch(`http://127.0.0.1:${state.controlPort}/${action}`, {
      method: action === "stop" ? "POST" : "GET",
      headers: { Authorization: `Bearer ${state.token}` }, signal: AbortSignal.timeout(3000), redirect: "error",
    });
    if (!response.ok) return null;
    const data = await response.json();
    if (data.application !== "ibanscan-preview" || (action === "status" && data.url !== state.url)) return null;
    return data;
  } catch { return null; }
}
async function freePort() {
  for (let port = 3000; port <= 3020; port++) {
    const free = await new Promise(resolveFree => {
      const server = createSocketServer();
      server.once("error", () => resolveFree(false));
      server.listen(port, "127.0.0.1", () => server.close(() => resolveFree(true)));
    });
    if (free) return port;
  }
  throw new Error("Le porte da 3000 a 3020 sono occupate. Chiudi una precedente anteprima e riprova.");
}
function sourceFingerprint() {
  const hash = createHash("sha256");
  function add(path) {
    if (!existsSync(path)) return;
    for (const item of readdirSync(path, { withFileTypes: true }).sort((a,b) => a.name.localeCompare(b.name))) {
      const full = join(path, item.name);
      if (item.isDirectory()) add(full);
      else if (item.isFile()) hash.update(full.slice(root.length)).update(readFileSync(full));
    }
  }
  for (const directory of ["app", "components", "lib", "locales", "styles", "public", "data"]) add(join(root, directory));
  for (const file of ["package.json", "package-lock.json", "next.config.ts", "tsconfig.json", ".env", ".env.local", ".env.production", ".env.production.local", "scripts/prepare-standalone.mjs"]) {
    const full = join(root, file);
    if (existsSync(full)) hash.update(file).update(readFileSync(full));
  }
  return hash.digest("hex");
}
function runNpm(command) {
  const npmCli = join(dirname(process.execPath), "node_modules", "npm", "bin", "npm-cli.js");
  if (!existsSync(npmCli)) throw new Error("npm non e disponibile accanto a Node.js. Ripara l'installazione di Node.js e riprova.");
  return new Promise((resolveRun, reject) => {
    const child = spawn(process.execPath, [npmCli, ...command], { cwd: root, stdio: "inherit", windowsHide: true, env: { ...process.env, NEXT_TELEMETRY_DISABLED: "1" } });
    child.once("error", reject);
    child.once("exit", code => code === 0 ? resolveRun() : reject(new Error(`Preparazione non riuscita (codice ${code}).`)));
  });
}
function openBrowser(url) {
  if (noBrowser) return;
  const parsed = new URL(url);
  if (parsed.hostname !== "127.0.0.1" || parsed.protocol !== "http:" || !/^\d+$/.test(parsed.port)
    || parsed.pathname !== "/" || parsed.username || parsed.password || parsed.hash || parsed.search) throw new Error("Indirizzo locale non valido.");
  // Only a loopback URL generated by this launcher is passed to the browser.
  const child = spawn("powershell.exe", ["-NoProfile", "-NonInteractive", "-Command", `Start-Process -FilePath '${url}'`], { stdio: "ignore", windowsHide: true });
  child.on("error", () => console.log(`Apri il browser su ${url}`));
  child.unref();
}

async function worker() {
  for (const file of [".env.production.local", ".env.local", ".env.production", ".env"]) if (existsSync(join(root, file))) process.loadEnvFile(join(root, file));
  const port = Number(process.argv[3]);
  if (!Number.isInteger(port) || port < 3000 || port > 3020) throw new Error("Porta non valida.");
  const url = `http://127.0.0.1:${port}/`;
  const token = randomBytes(32).toString("hex");
  let closing = false;
  const child = spawn(process.execPath, [serverEntry], {
    cwd: root, stdio: "inherit", windowsHide: true,
    env: { ...process.env, NODE_ENV: "production", HOSTNAME: "127.0.0.1", PORT: String(port), APP_URL: url.slice(0,-1),
      NEXT_TELEMETRY_DISABLED: "1", RATE_LIMIT_ALLOW_SINGLE_INSTANCE: "true", RATE_LIMIT_HASH_SECRET: process.env.RATE_LIMIT_HASH_SECRET || randomBytes(32).toString("hex") },
  });
  const controlServer = createServer((request, response) => {
    const supplied = request.headers.authorization;
    const expected = `Bearer ${token}`;
    const host = request.headers.host;
    const authenticated = typeof supplied === "string" && Buffer.byteLength(supplied) === Buffer.byteLength(expected) && timingSafeEqual(Buffer.from(supplied), Buffer.from(expected));
    if (!authenticated || request.headers.origin || host !== `127.0.0.1:${controlServer.address()?.port}`) { response.writeHead(404); response.end(); return; }
    response.setHeader("Content-Type", "application/json"); response.setHeader("Cache-Control", "no-store");
    if (request.method === "GET" && request.url === "/status") { response.end(JSON.stringify({ application: "ibanscan-preview", url })); return; }
    if (request.method === "POST" && request.url === "/stop") { response.end(JSON.stringify({ application: "ibanscan-preview", stopped: true })); void shutdown(); return; }
    response.writeHead(404); response.end();
  });
  controlServer.requestTimeout = 5000;
  controlServer.headersTimeout = 5000;
  controlServer.maxHeadersCount = 10;
  async function shutdown() {
    if (closing) return;
    closing = true;
    if (readState()?.token === token) { try { unlinkSync(statePath); } catch { /* Already removed. */ } }
    controlServer.close(); controlServer.closeIdleConnections();
    child.kill("SIGTERM");
    const force = setTimeout(() => { child.kill("SIGKILL"); process.exit(0); }, 5000);
    child.once("exit", () => { clearTimeout(force); process.exit(0); });
  }
  child.once("error", error => { console.error(error.message); void shutdown(); });
  child.once("exit", code => { if (!closing) { console.log(`Server terminato (${code}).`); void shutdown(); } });
  for (const signal of ["SIGINT", "SIGTERM"]) process.on(signal, shutdown);
  await new Promise(resolveListen => controlServer.listen(0, "127.0.0.1", resolveListen));
  for (let attempt=0; attempt<120; attempt++) {
    if (closing) return;
    try {
      const health = await fetch(`${url}api/health`, { signal: AbortSignal.timeout(1000) });
      const body = await health.json();
      if (health.ok && body.status === "ok" && body.validation === "available") {
        const state = { controlPort: controlServer.address().port, token, url, startedAt: new Date().toISOString() };
        writeFileSync(statePath + ".tmp", JSON.stringify(state), { mode: 0o600 }); renameSync(statePath + ".tmp", statePath);
        console.log(`IBANScan pronto: ${url}`); return;
      }
    } catch { /* Wait until the owned Next.js child has bound its port. */ }
    await delay(250);
  }
  console.error("Il server non e diventato disponibile entro il tempo previsto."); await shutdown();
}

async function start() {
  if (Number(process.versions.node.split(".")[0]) < 22) throw new Error("Questo launcher richiede Node.js 22 o successivo.");
  const running = await control(readState(), "status");
  if (running) { console.log(`IBANScan e gia avviato: ${running.url}`); openBrowser(running.url); return; }
  let lock;
  try { lock = openSync(lockPath, "wx"); writeFileSync(lock, String(process.pid)); }
  catch {
    let alive = false;
    try { const pid=Number(readFileSync(lockPath,"utf8")); if(Number.isInteger(pid)&&pid>0){process.kill(pid,0);alive=true;} } catch { /* Stale preparation lock. */ }
    if (alive) { console.log("IBANScan si sta gia preparando. Attendi il completamento della prima finestra."); return; }
    try { unlinkSync(lockPath); } catch { /* No stale lock. */ }
    lock = openSync(lockPath, "wx"); writeFileSync(lock, String(process.pid));
  }
  try {
    const existing = await control(readState(), "status");
    if (existing) { console.log(`IBANScan e gia avviato: ${existing.url}`); openBrowser(existing.url); return; }
    console.log("IBANScan - Anteprima locale\n");
    if (!existsSync(join(root,"node_modules","next","package.json"))) { console.log("Installazione delle dipendenze...\n"); await runNpm(["ci"]); }
    const fingerprint = sourceFingerprint();
    const lastFingerprint = existsSync(fingerprintPath) ? readFileSync(fingerprintPath,"utf8") : "";
    if (!existsSync(serverEntry) || fingerprint !== lastFingerprint) {
      console.log("Preparazione della versione di produzione. Il primo avvio puo richiedere qualche minuto.\n");
      await runNpm(["run","build"]); writeFileSync(fingerprintPath, fingerprint);
    }
    const port = await freePort();
    const log = openSync(logPath, "a");
    const child = spawn(process.execPath, [fileURLToPath(import.meta.url), "worker", String(port)], { cwd: root, detached: true, stdio: ["ignore", log, log], windowsHide: true });
    closeSync(log); child.unref();
    let launchError;
    child.once("error", error => { launchError=error; });
    for (let attempt=0;attempt<160;attempt++) {
      if (launchError) throw launchError;
      const ready = await control(readState(), "status");
      if (ready) { console.log(`\nSito pronto: ${ready.url}\nPer arrestarlo: doppio clic su "Ferma IBANScan.cmd".\nLog: ${logPath}`); openBrowser(ready.url); return; }
      await delay(250);
    }
    throw new Error(`Il server non risponde. Consulta ${logPath}`);
  } finally { closeSync(lock); try { unlinkSync(lockPath); } catch { /* Already removed. */ } }
}
try {
  if (mode === "worker") await worker();
  else if (mode === "stop") {
    const state=readState();
    if (await control(state,"stop")) {
      for(let attempt=0;attempt<30;attempt++){if(!await control(state,"status"))break;await delay(100);}
      console.log("IBANScan e stato arrestato.");
    } else console.log("Nessuna anteprima IBANScan avviata da questo launcher.");
  } else if(mode === "start") await start();
  else throw new Error("Comando non riconosciuto. Usa start oppure stop.");
} catch (error) { console.error(error instanceof Error ? error.message : "Errore di avvio."); process.exitCode=1; }
