import assert from "node:assert/strict";
import { execFile } from "node:child_process";
import { promisify } from "node:util";
import { readFileSync, existsSync } from "node:fs";
const run = promisify(execFile);
const launcher = "scripts/preview-launcher.mjs";
const readState = () => JSON.parse(readFileSync(".local/preview.json", "utf8"));
await run(process.execPath, [launcher, "start", "--no-browser"]);
const state = readState();
const control = `http://127.0.0.1:${state.controlPort}`;
const auth = { Authorization: `Bearer ${state.token}` };
assert.equal(new URL(state.url).hostname, "127.0.0.1");
assert.equal((await fetch(state.url)).status, 200);
assert.equal((await fetch(`${state.url}api/health`)).status, 200);
assert.equal((await fetch(`${control}/stop`, { method: "POST" })).status, 404);
assert.equal((await fetch(`${control}/stop`, { method: "POST", headers: { Authorization: "Bearer wrong" } })).status, 404);
assert.equal((await fetch(`${control}/stop`, { method: "POST", headers: { ...auth, Origin: "https://example.org" } })).status, 404);
assert.equal((await fetch(`${control}/stop`, { headers: auth })).status, 404);
await run(process.execPath, [launcher, "start", "--no-browser"]);
assert.equal(readState().controlPort, state.controlPort);
assert.equal(readState().token, state.token);
await run(process.execPath, [launcher, "stop"]);
assert.equal(existsSync(".local/preview.json"), false);
await assert.rejects(fetch(`${control}/status`, { headers: auth, signal: AbortSignal.timeout(2000) }));
await run(process.execPath, [launcher, "stop"]);
await run(process.execPath, [launcher, "start", "--no-browser"]);
const restarted = readState();
assert.notEqual(restarted.token, state.token);
assert.equal((await fetch(restarted.url)).status, 200);
console.log("Launcher verified: starts, reuses existing server, rejects unauthorized shutdown, stops, and restarts. Ready at " + restarted.url);
